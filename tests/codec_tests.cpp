using Bytes = std::vector<std::uint8_t>;
void check(bool value, const char* message) { if (!value) throw std::runtime_error(message); }
template<class F> void rejects(F action, const char* message) {
    try { action(); } catch (const std::runtime_error&) { return; }
    throw std::runtime_error(message);
}
struct ScopedCurrentDirectory {
    const std::filesystem::path previous = std::filesystem::current_path();
    explicit ScopedCurrentDirectory(const std::filesystem::path& path) { std::filesystem::current_path(path); }
    ~ScopedCurrentDirectory() {
        std::error_code ignored;
        std::filesystem::current_path(previous, ignored);
    }
};
void byte(Bytes& b, std::uint8_t v) { b.push_back(v); }
void word(Bytes& b, std::uint16_t v) { byte(b, static_cast<std::uint8_t>(v)); byte(b, static_cast<std::uint8_t>(v >> 8)); }
void dword(Bytes& b, std::uint32_t v) { word(b, static_cast<std::uint16_t>(v)); word(b, static_cast<std::uint16_t>(v >> 16)); }
void fixed(Bytes& b, const std::string& s, std::size_t count) {
    b.insert(b.end(), s.begin(), s.end()); b.insert(b.end(), count - s.size(), 0);
}
void patch32(Bytes& b, std::size_t offset, std::uint32_t v) {
    for (unsigned i = 0; i < 4; ++i) b.at(offset + i) = static_cast<std::uint8_t>(v >> (i * 8));
}

// Independent byte fixture, not generated by the codec being tested. Both
// delta streams deliberately wrap around the signed 8/16-bit boundaries.
Bytes referenceXm() {
    Bytes b;
    fixed(b, "Extended Module: ", 17); fixed(b, "Reference", 20); byte(b, 0x1A);
    fixed(b, "Independent fixture", 20); word(b, 0x0104); dword(b, 276);
    word(b, 1); word(b, 0); word(b, 1); word(b, 1); word(b, 1);
    word(b, 1); word(b, 6); word(b, 125); b.insert(b.end(), 256, 0);
    dword(b, 9); byte(b, 0); word(b, 1); word(b, 6);
    b.insert(b.end(), {0x9F, 49, 1, 0xF3, 0x23, 0x7F});
    dword(b, 263); fixed(b, "Two samples", 22); byte(b, 0); word(b, 2); dword(b, 40);
    b.insert(b.end(), 96 + 96 + 14, 0); word(b, 0); b.insert(b.end(), 22, 0);
    dword(b, 4); dword(b, 1); dword(b, 2); byte(b, 64); byte(b, 0);
    byte(b, 1); byte(b, 128); byte(b, 0); byte(b, 0); fixed(b, "Eight", 22);
    dword(b, 8); dword(b, 2); dword(b, 4); byte(b, 64); byte(b, 0);
    byte(b, 0x12); byte(b, 128); byte(b, 0); byte(b, 0); fixed(b, "Unused sixteen", 22);
    b.insert(b.end(), {0x80, 0xFF, 0x81, 0xFF});
    b.insert(b.end(), {0x00, 0x80, 0xFF, 0xFF, 0x01, 0x80, 0xFF, 0xFF});
    return b;
}

Bytes stereoWav8() {
    Bytes b;
    fixed(b, "RIFF", 4); dword(b, 0); fixed(b, "WAVE", 4);
    fixed(b, "JUNK", 4); dword(b, 3); b.insert(b.end(), {1, 2, 3, 0});
    fixed(b, "fmt ", 4); dword(b, 16); word(b, 1); word(b, 2);
    dword(b, 8363); dword(b, 16726); word(b, 2); word(b, 8);
    fixed(b, "data", 4); dword(b, 4); b.insert(b.end(), {0, 255, 128, 128});
    patch32(b, 4, static_cast<std::uint32_t>(b.size() - 8));
    return b;
}

Bytes legacyXm(std::uint16_t version) {
    const auto modern = referenceXm();
    Bytes b(modern.begin(), modern.begin() + 336);
    b[58] = static_cast<std::uint8_t>(version); b[59] = static_cast<std::uint8_t>(version >> 8);
    b[72] = 2; // Include a second, empty instrument to exercise all-headers-first.
    b.insert(b.end(), modern.begin() + 351, modern.begin() + 694);
    dword(b, 29); fixed(b, "Old empty instrument", 22); byte(b, 0); word(b, 0);
    if (version == 0x0102) {
        dword(b, 8); byte(b, 0); byte(b, 0); word(b, 6); // byte rows = rows minus one
        b.insert(b.end(), modern.begin() + 345, modern.begin() + 351);
    } else b.insert(b.end(), modern.begin() + 336, modern.begin() + 351);
    b.insert(b.end(), modern.begin() + 694, modern.end());
    return b;
}

// Remove only unused order bytes from a full independent XM fixture. The
// following pattern/instrument bytes move with the declared header boundary.
Bytes compactXmHeader(Bytes bytes, std::size_t storedOrders) {
    check(storedOrders <= 256, "Invalid compact fixture order count");
    bytes.erase(bytes.begin() + 80 + storedOrders, bytes.begin() + 336);
    patch32(bytes, 60, static_cast<std::uint32_t>(20 + storedOrders));
    return bytes;
}
